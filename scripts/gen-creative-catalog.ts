// Generates server/src/services/creative-catalog.generated.ts from the Creative
// Studio picker (apps/desktop/src/lib/creative-models.ts), so AURA chooses from
// exactly the models a user can pick, per feature.
//
//   npx tsx scripts/gen-creative-catalog.ts          write the file
//   npx tsx scripts/gen-creative-catalog.ts --check  exit 1 if it is stale
//
// server/test/creative-catalog-sync.spec.ts fails when the picker changes and
// this file was not regenerated.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { MODELS_BY_SECTION, effectivePerImage, type ModelOption } from '../apps/desktop/src/lib/creative-models';

export function buildCatalogSource(): string {
  const keep: (keyof ModelOption)[] = ['value', 'label', 'vendor', 'hint', 'provider', 'model', 'quality',
    'perImage', 'perSec', 'perSec1080', 'minSeconds', 'maxSeconds', 'supports1080', 'maxSize', 'tier'];
  const out: Record<string, unknown[]> = {};
  for (const [section, list] of Object.entries(MODELS_BY_SECTION)) {
    out[section] = list.filter((o) => o.value !== 'auto').map((o) => {
      const e: Record<string, unknown> = {};
      for (const k of keep) if (o[k] !== undefined) e[k] = o[k];
      if (!section.includes('video')) {
        const sizes = { '1K': effectivePerImage(o, '1K'), '2K': effectivePerImage(o, '2K'), '4K': effectivePerImage(o, '4K') };
        if (sizes['1K'] !== undefined) e.perImageBySize = sizes;
      }
      return e;
    });
  }
  return `// GENERATED by scripts/gen-creative-catalog.ts from apps/desktop/src/lib/creative-models.ts.
// Do not edit by hand. Regenerate: npx tsx scripts/gen-creative-catalog.ts
// Every model a user can pick in Creative Studio, per feature. AURA's engine
// director chooses from exactly this list on Auto.

export type CatalogSection = 'text-to-image' | 'image-edit' | 'upscale' | 'text-to-video' | 'image-to-video' | 'reference-video';

export interface CatalogModel {
  value: string;
  label: string;
  vendor?: string;
  hint: string;
  provider?: 'gemini' | 'xai' | 'dashscope' | 'vertex' | 'minimax' | 'byteplus';
  model?: string;
  quality?: 'standard' | 'ultra';
  perImage?: number;
  perImageBySize?: { '1K'?: number; '2K'?: number; '4K'?: number };
  perSec?: number;
  perSec1080?: number;
  minSeconds?: number;
  maxSeconds?: number;
  supports1080?: boolean;
  maxSize?: '1K' | '2K' | '4K';
  tier?: 'draft' | 'hd';
}

export const CREATIVE_CATALOG: Record<CatalogSection, CatalogModel[]> = ${JSON.stringify(out, null, 2)};
`;
}

if (process.argv[1] && process.argv[1].includes('gen-creative-catalog')) {
  const target = resolve(dirname(process.argv[1]), '../server/src/services/creative-catalog.generated.ts');
  const src = buildCatalogSource();
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return readFileSync(target, 'utf8'); } catch { return ''; } })();
    if (cur !== src) { console.error('creative-catalog.generated.ts is stale: run npx tsx scripts/gen-creative-catalog.ts'); process.exit(1); }
    console.log('creative catalog is current');
  } else {
    writeFileSync(target, src);
    console.log('wrote', target);
  }
}
