import PptxGenJS from 'pptxgenjs';
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { db } from '../db/prisma.js';
import { type Job, updateJob } from './queue.js';

const EXPORT_DIR = path.resolve(process.cwd(), 'uploads', 'exports');
fs.mkdirSync(EXPORT_DIR, { recursive: true });

// Platform → brand color mapping
const PLATFORM_COLORS: Record<string, string> = {
  instagram: 'E1306C',
  linkedin: '0A66C2',
  tiktok: '333333',
  x: '1DA1F2',
  facebook: '4267B2',
};

function getPlatformColor(platform: string): string {
  const key = platform.toLowerCase().replace(/\s/g, '');
  return PLATFORM_COLORS[key] || '8B5CF6';
}

export async function exportWorker(job: Job): Promise<{ exportJobId: string; fileUrl: string }> {
  const { clientId, calendarMonthId, type } = job.data;

  // 1. Fetch data
  updateJob(job.id, { progress: 10 });
  const calendarMonth = await db.calendarMonth.findUnique({
    where: { id: calendarMonthId },
    include: { posts: { orderBy: { date: 'asc' } } },
  });
  if (!calendarMonth) throw new Error('Calendar month not found');

  const client = await db.client.findUnique({ where: { id: clientId } });
  if (!client) throw new Error('Client not found');

  updateJob(job.id, { progress: 20 });

  if (type === 'pptx') {
    return await generatePptx(job, client, calendarMonth);
  }
  throw new Error(`Unsupported export type: ${type}`);
}

async function generatePptx(
  job: Job,
  client: any,
  calendarMonth: any & { posts: any[] },
): Promise<{ exportJobId: string; fileUrl: string }> {
  const pptx = new PptxGenJS();
  pptx.author = 'Radix AI Content Planner';
  pptx.title = `${client.name} — ${calendarMonth.month} Content Calendar`;
  pptx.subject = 'AI-Generated Content Calendar';

  // ─── Slide 1: Title ─────────────────────────────────────────────
  updateJob(job.id, { progress: 30 });
  const titleSlide = pptx.addSlide();
  titleSlide.background = { color: '0A0A0A' };

  titleSlide.addText(client.name, {
    x: 0.8, y: 1.5, w: 8.4, h: 1,
    fontSize: 36, fontFace: 'Arial',
    color: 'FFFFFF', bold: true,
  });
  titleSlide.addText(`${calendarMonth.month} Content Calendar`, {
    x: 0.8, y: 2.5, w: 8.4, h: 0.6,
    fontSize: 20, fontFace: 'Arial',
    color: '8B5CF6',
  });
  titleSlide.addText(`${calendarMonth.posts.length} content pieces across ${[...new Set(calendarMonth.posts.map((p: any) => p.platform))].length} platforms`, {
    x: 0.8, y: 3.3, w: 8.4, h: 0.5,
    fontSize: 14, fontFace: 'Arial',
    color: '71717A',
  });

  // Strategy overview if available
  const strategy = calendarMonth.strategy as any;
  if (strategy?.overview) {
    titleSlide.addText(strategy.overview.slice(0, 300) + (strategy.overview.length > 300 ? '...' : ''), {
      x: 0.8, y: 4.2, w: 8.4, h: 1.2,
      fontSize: 11, fontFace: 'Arial',
      color: 'A1A1AA',
      valign: 'top',
    });
  }

  titleSlide.addText('Generated by Radix AI Content Planner', {
    x: 0.8, y: 6.8, w: 8.4, h: 0.3,
    fontSize: 9, fontFace: 'Arial',
    color: '52525B',
  });

  // ─── Slide 2: Calendar Overview ─────────────────────────────────
  updateJob(job.id, { progress: 40 });
  const overviewSlide = pptx.addSlide();
  overviewSlide.background = { color: '0A0A0A' };
  overviewSlide.addText('Calendar Overview', {
    x: 0.8, y: 0.3, w: 8.4, h: 0.6,
    fontSize: 22, fontFace: 'Arial',
    color: 'FFFFFF', bold: true,
  });

  // Platform breakdown table
  const platformCounts: Record<string, number> = {};
  for (const post of calendarMonth.posts) {
    platformCounts[post.platform] = (platformCounts[post.platform] || 0) + 1;
  }

  const tableRows: any[][] = [
    [
      { text: 'Platform', options: { bold: true, color: 'FFFFFF', fill: { color: '18181B' }, fontSize: 11 } },
      { text: 'Posts', options: { bold: true, color: 'FFFFFF', fill: { color: '18181B' }, fontSize: 11 } },
      { text: 'Formats', options: { bold: true, color: 'FFFFFF', fill: { color: '18181B' }, fontSize: 11 } },
    ],
  ];

  for (const [platform, count] of Object.entries(platformCounts)) {
    const formats = [...new Set(calendarMonth.posts.filter((p: any) => p.platform === platform).map((p: any) => p.format))].join(', ');
    tableRows.push([
      { text: platform, options: { color: getPlatformColor(platform), fontSize: 11 } },
      { text: String(count), options: { color: 'D4D4D8', fontSize: 11 } },
      { text: formats || '—', options: { color: 'A1A1AA', fontSize: 10 } },
    ]);
  }

  overviewSlide.addTable(tableRows, {
    x: 0.8, y: 1.2, w: 8.4,
    border: { type: 'solid', pt: 0.5, color: '27272A' },
    colW: [3, 1.5, 3.9],
    rowH: 0.45,
  });

  // ─── Post slides ────────────────────────────────────────────────
  const totalPosts = calendarMonth.posts.length;
  for (let i = 0; i < totalPosts; i++) {
    const post = calendarMonth.posts[i];
    const progress = 50 + Math.floor((i / totalPosts) * 40);
    updateJob(job.id, { progress });

    const slide = pptx.addSlide();
    slide.background = { color: '0A0A0A' };

    // Post number + date
    slide.addText(`Post ${i + 1}/${totalPosts}`, {
      x: 0.8, y: 0.2, w: 3, h: 0.35,
      fontSize: 9, fontFace: 'Arial', color: '52525B',
    });
    slide.addText(post.date || '', {
      x: 5.5, y: 0.2, w: 4, h: 0.35,
      fontSize: 9, fontFace: 'Arial', color: '52525B', align: 'right',
    });

    // Platform badge + Title
    const platColor = getPlatformColor(post.platform);
    slide.addShape(pptx.ShapeType.roundRect, {
      x: 0.8, y: 0.6, w: 1.5, h: 0.35,
      fill: { color: platColor }, rectRadius: 0.1,
    });
    slide.addText(post.platform?.toUpperCase() || '', {
      x: 0.8, y: 0.6, w: 1.5, h: 0.35,
      fontSize: 8, fontFace: 'Arial', color: 'FFFFFF', bold: true, align: 'center',
    });

    if (post.format) {
      slide.addText(post.format, {
        x: 2.5, y: 0.6, w: 2, h: 0.35,
        fontSize: 9, fontFace: 'Arial', color: '71717A',
      });
    }

    slide.addText(post.title || 'Untitled', {
      x: 0.8, y: 1.1, w: 8.4, h: 0.5,
      fontSize: 18, fontFace: 'Arial', color: 'FFFFFF', bold: true,
    });

    // Pillar
    if (post.pillar) {
      slide.addText(`Pillar: ${post.pillar}`, {
        x: 0.8, y: 1.6, w: 8.4, h: 0.3,
        fontSize: 10, fontFace: 'Arial', color: '8B5CF6',
      });
    }

    // Hook
    if (post.hook) {
      slide.addText(`Hook: "${post.hook}"`, {
        x: 0.8, y: 1.95, w: 8.4, h: 0.35,
        fontSize: 11, fontFace: 'Arial', color: 'FBBF24', italic: true,
      });
    }

    // Key message
    if (post.keyMessage) {
      slide.addText('KEY MESSAGE', {
        x: 0.8, y: 2.4, w: 2, h: 0.25,
        fontSize: 8, fontFace: 'Arial', color: 'F59E0B', bold: true,
      });
      slide.addText(post.keyMessage, {
        x: 0.8, y: 2.65, w: 8.4, h: 0.5,
        fontSize: 10, fontFace: 'Arial', color: 'FDE68A',
        valign: 'top',
      });
    }

    // Caption
    const captionY = post.keyMessage ? 3.25 : 2.4;
    slide.addText('CAPTION', {
      x: 0.8, y: captionY, w: 2, h: 0.25,
      fontSize: 8, fontFace: 'Arial', color: '71717A', bold: true,
    });
    const captionText = (post.caption || '').slice(0, 600) + ((post.caption || '').length > 600 ? '...' : '');
    slide.addText(captionText, {
      x: 0.8, y: captionY + 0.25, w: 8.4, h: 1.6,
      fontSize: 10, fontFace: 'Arial', color: 'D4D4D8',
      valign: 'top', shrinkText: true,
    });

    // CTA
    if (post.cta) {
      slide.addText(`CTA: ${post.cta}`, {
        x: 0.8, y: 5.4, w: 8.4, h: 0.35,
        fontSize: 10, fontFace: 'Arial', color: '34D399', bold: true,
      });
    }

    // Visual direction
    if (post.visualDirection) {
      slide.addText('VISUAL DIRECTION', {
        x: 0.8, y: 5.85, w: 2.5, h: 0.25,
        fontSize: 8, fontFace: 'Arial', color: '71717A', bold: true,
      });
      slide.addText((post.visualDirection || '').slice(0, 300), {
        x: 0.8, y: 6.1, w: 8.4, h: 0.7,
        fontSize: 9, fontFace: 'Arial', color: 'A1A1AA',
        valign: 'top', shrinkText: true,
      });
    }

    // Hashtags + Timing footer
    const footerParts: string[] = [];
    if (post.hashtags?.length) footerParts.push(post.hashtags.map((h: string) => `#${h.replace(/^#/, '')}`).join(' '));
    if (post.timing) footerParts.push(`| ${post.timing}`);
    if (footerParts.length) {
      slide.addText(footerParts.join(' '), {
        x: 0.8, y: 6.85, w: 8.4, h: 0.3,
        fontSize: 8, fontFace: 'Arial', color: '52525B',
      });
    }
  }

  // ─── Write file ─────────────────────────────────────────────────
  updateJob(job.id, { progress: 92 });
  const hash = crypto.randomBytes(6).toString('hex');
  const slug = client.slug || client.name.toLowerCase().replace(/\s+/g, '-');
  const filename = `${slug}_${calendarMonth.month.replace(/\s+/g, '_')}_${hash}.pptx`;
  const filePath = path.join(EXPORT_DIR, filename);
  await pptx.writeFile({ fileName: filePath });

  const fileUrl = `/uploads/exports/${filename}`;

  // Save to ExportJob table
  const exportRecord = await db.exportJob.create({
    data: {
      clientId: client.id,
      calendarMonthId: calendarMonth.id,
      type: 'pptx',
      status: 'completed',
      fileUrl,
    },
  });

  updateJob(job.id, { progress: 100 });
  return { exportJobId: exportRecord.id, fileUrl };
}
