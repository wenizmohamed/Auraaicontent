// Monthly client report worker — generates a PPTX deliverable for an agency
// to send the client. Differs from export.worker.ts: this is a *report*
// (cover + strategy + per-post slides + summary), not the raw calendar dump.
//
// Theme system: 3 named themes selectable per Client. Default is 'aura'
// (warm amber accent matching the dashboard). Themes are pure data — no
// business logic, just RGB tuples + font defaults.

import PptxGenJS from 'pptxgenjs';
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { db } from '../db/prisma.js';
import { type Job, updateJob } from './queue.js';

const REPORT_DIR = path.resolve(process.cwd(), 'uploads', 'reports');
fs.mkdirSync(REPORT_DIR, { recursive: true });

export type ReportTheme = 'aura' | 'dark' | 'pitch';

interface Theme {
  bg: string;        // slide background hex
  fg: string;        // primary text hex
  muted: string;     // secondary text hex
  accent: string;    // accent (titles, brand color)
  accentSoft: string;// accent surfaces / pillars
  card: string;      // card / table cell fill
  rule: string;      // hairline rule
  font: string;
}

const THEMES: Record<ReportTheme, Theme> = {
  // Light, warm, agency-deck. Matches Radix Media dashboard.
  aura:  { bg: 'FAFAF7', fg: '0F0F0F', muted: '6B7280', accent: 'D97706', accentSoft: 'FEF3C7', card: 'F3F4F6', rule: 'E5E7EB', font: 'Inter' },
  // The existing internal export.worker.ts vibe — black + violet.
  dark:  { bg: '0A0A0A', fg: 'FFFFFF', muted: 'A1A1AA', accent: '8B5CF6', accentSoft: '4C1D95', card: '18181B', rule: '27272A', font: 'Arial' },
  // Sales pitch — high contrast white on near-black with electric blue accent.
  pitch: { bg: '0E1116', fg: 'FFFFFF', muted: '9CA3AF', accent: '38BDF8', accentSoft: '0C4A6E', card: '1F2937', rule: '374151', font: 'Inter' },
};

const PLATFORM_COLORS: Record<string, string> = {
  instagram: 'E1306C',
  linkedin: '0A66C2',
  tiktok: '111111',
  x: '1DA1F2',
  facebook: '4267B2',
};

function platformColor(p: string): string {
  return PLATFORM_COLORS[p?.toLowerCase().replace(/\s/g, '')] || '8B5CF6';
}

function trim(s: string | null | undefined, max: number): string {
  if (!s) return '';
  return s.length > max ? s.slice(0, max - 1) + '…' : s;
}

function parseJsonish(value: unknown): any {
  if (!value) return null;
  if (typeof value === 'string') {
    try { return JSON.parse(value); } catch { return value; }
  }
  return value;
}

export async function reportWorker(job: Job): Promise<{ fileUrl: string; filename: string; postCount: number }> {
  const { clientId, calendarMonthId, theme: themeName = 'aura' } = job.data;

  updateJob(job.id, { progress: 5 });

  const calendarMonth = await db.calendarMonth.findUnique({
    where: { id: calendarMonthId },
    include: { posts: { orderBy: { date: 'asc' } } },
  });
  if (!calendarMonth) throw new Error('Calendar month not found');

  const client = await db.client.findUnique({
    where: { id: clientId },
    include: { brief: true },
  });
  if (!client) throw new Error('Client not found');

  updateJob(job.id, { progress: 15 });

  const theme = THEMES[(themeName as ReportTheme) in THEMES ? (themeName as ReportTheme) : 'aura'];
  const brief = client.brief;
  const posts = calendarMonth.posts;
  const totalPosts = posts.length;

  const pptx = new PptxGenJS();
  pptx.author = 'Radix Media';
  pptx.title = `${client.name} — ${calendarMonth.month} Monthly Report`;
  pptx.subject = 'AI Content Planner monthly delivery';
  pptx.layout = 'LAYOUT_WIDE';

  // ─── Slide 1: Cover ──────────────────────────────────────────────────
  updateJob(job.id, { progress: 25 });
  const cover = pptx.addSlide();
  cover.background = { color: theme.bg };

  cover.addShape(pptx.ShapeType.rect, {
    x: 0, y: 0, w: 13.33, h: 0.5, fill: { color: theme.accent }, line: { color: theme.accent },
  });

  cover.addText('MONTHLY CONTENT REPORT', {
    x: 0.7, y: 1.1, w: 12, h: 0.4,
    fontSize: 11, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 4,
  });

  cover.addText(client.name, {
    x: 0.7, y: 1.6, w: 12, h: 1.4,
    fontSize: 54, fontFace: theme.font, color: theme.fg, bold: true,
  });

  cover.addText(calendarMonth.month, {
    x: 0.7, y: 3.1, w: 12, h: 0.6,
    fontSize: 24, fontFace: theme.font, color: theme.accent,
  });

  const platforms = [...new Set(posts.map((p: any) => p.platform).filter(Boolean))];
  cover.addText(`${totalPosts} posts · ${platforms.length} ${platforms.length === 1 ? 'platform' : 'platforms'} · ${platforms.join(' · ')}`, {
    x: 0.7, y: 4.0, w: 12, h: 0.4,
    fontSize: 13, fontFace: theme.font, color: theme.muted,
  });

  cover.addText(`Generated by Radix Media · ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}`, {
    x: 0.7, y: 6.8, w: 12, h: 0.3,
    fontSize: 9, fontFace: theme.font, color: theme.muted, italic: true,
  });

  // ─── Slide 2: Strategy ───────────────────────────────────────────────
  updateJob(job.id, { progress: 35 });
  if (brief) {
    const strategy = pptx.addSlide();
    strategy.background = { color: theme.bg };

    strategy.addText('STRATEGIC FOUNDATION', {
      x: 0.7, y: 0.5, w: 12, h: 0.3,
      fontSize: 10, fontFace: theme.font, color: theme.accent, bold: true, charSpacing: 4,
    });
    strategy.addText('Brief at a glance', {
      x: 0.7, y: 0.85, w: 12, h: 0.7,
      fontSize: 32, fontFace: theme.font, color: theme.fg, bold: true,
    });

    if (brief.objective) {
      strategy.addText('OBJECTIVE', {
        x: 0.7, y: 1.9, w: 5.8, h: 0.3,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      strategy.addText(trim(brief.objective, 360), {
        x: 0.7, y: 2.2, w: 5.8, h: 1.5,
        fontSize: 12, fontFace: theme.font, color: theme.fg, valign: 'top',
      });
    }
    if (brief.audience) {
      strategy.addText('AUDIENCE', {
        x: 6.85, y: 1.9, w: 5.8, h: 0.3,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      strategy.addText(trim(brief.audience, 360), {
        x: 6.85, y: 2.2, w: 5.8, h: 1.5,
        fontSize: 12, fontFace: theme.font, color: theme.fg, valign: 'top',
      });
    }
    if (brief.tone) {
      strategy.addText('TONE OF VOICE', {
        x: 0.7, y: 3.9, w: 5.8, h: 0.3,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      strategy.addText(trim(brief.tone, 280), {
        x: 0.7, y: 4.2, w: 5.8, h: 1.2,
        fontSize: 11, fontFace: theme.font, color: theme.fg, valign: 'top',
      });
    }

    // Pillars row
    const pillars = parseJsonish(brief.pillars) || [];
    if (Array.isArray(pillars) && pillars.length > 0) {
      strategy.addText('CONTENT PILLARS', {
        x: 6.85, y: 3.9, w: 5.8, h: 0.3,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      const pillarText = pillars
        .slice(0, 6)
        .map((p: any, i: number) => `${i + 1}. ${typeof p === 'string' ? p : (p?.name || p?.title || JSON.stringify(p))}`)
        .join('\n');
      strategy.addText(pillarText, {
        x: 6.85, y: 4.2, w: 5.8, h: 2,
        fontSize: 11, fontFace: theme.font, color: theme.fg, valign: 'top',
      });
    }
  }

  // ─── Per-post slides ─────────────────────────────────────────────────
  for (let i = 0; i < totalPosts; i++) {
    const post: any = posts[i];
    updateJob(job.id, { progress: 40 + Math.floor((i / Math.max(totalPosts, 1)) * 50) });

    const slide = pptx.addSlide();
    slide.background = { color: theme.bg };

    // Header bar
    slide.addText(`Post ${i + 1} / ${totalPosts}`, {
      x: 0.7, y: 0.4, w: 4, h: 0.3,
      fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
    });
    slide.addText(post.date || '', {
      x: 9.0, y: 0.4, w: 3.6, h: 0.3,
      fontSize: 9, fontFace: theme.font, color: theme.muted, align: 'right',
    });

    // Platform badge
    const platCol = platformColor(post.platform || '');
    slide.addShape(pptx.ShapeType.roundRect, {
      x: 0.7, y: 0.85, w: 1.4, h: 0.35,
      fill: { color: platCol }, line: { color: platCol }, rectRadius: 0.05,
    });
    slide.addText((post.platform || '').toUpperCase(), {
      x: 0.7, y: 0.85, w: 1.4, h: 0.35,
      fontSize: 9, fontFace: theme.font, color: 'FFFFFF', bold: true, align: 'center', valign: 'middle',
    });
    if (post.format) {
      slide.addText(post.format, {
        x: 2.25, y: 0.85, w: 4, h: 0.35,
        fontSize: 10, fontFace: theme.font, color: theme.muted, valign: 'middle',
      });
    }
    if (post.pillar) {
      slide.addShape(pptx.ShapeType.roundRect, {
        x: 9.4, y: 0.85, w: 3.2, h: 0.35,
        fill: { color: theme.accentSoft }, line: { color: theme.accentSoft }, rectRadius: 0.05,
      });
      slide.addText(post.pillar, {
        x: 9.4, y: 0.85, w: 3.2, h: 0.35,
        fontSize: 9, fontFace: theme.font, color: theme.accent, bold: true, align: 'center', valign: 'middle',
      });
    }

    // Title
    slide.addText(post.title || 'Untitled', {
      x: 0.7, y: 1.4, w: 12, h: 0.7,
      fontSize: 26, fontFace: theme.font, color: theme.fg, bold: true,
    });

    // Hook
    if (post.hook) {
      slide.addText(`"${trim(post.hook, 200)}"`, {
        x: 0.7, y: 2.2, w: 12, h: 0.6,
        fontSize: 14, fontFace: theme.font, color: theme.accent, italic: true,
      });
    }

    // Caption block
    const captionY = post.hook ? 2.95 : 2.2;
    slide.addText('CAPTION', {
      x: 0.7, y: captionY, w: 4, h: 0.25,
      fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
    });
    slide.addText(trim(post.caption || '', 700), {
      x: 0.7, y: captionY + 0.3, w: 7.5, h: 3.6,
      fontSize: 11, fontFace: theme.font, color: theme.fg, valign: 'top', shrinkText: true,
    });

    // Right column: visual direction + cta + hashtags
    const colX = 8.5;
    let colY = captionY;
    if (post.visualDirection) {
      slide.addText('VISUAL DIRECTION', {
        x: colX, y: colY, w: 4, h: 0.25,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      slide.addText(trim(post.visualDirection, 280), {
        x: colX, y: colY + 0.3, w: 4, h: 1.6,
        fontSize: 10, fontFace: theme.font, color: theme.fg, valign: 'top', shrinkText: true,
      });
      colY += 2.0;
    }
    if (post.cta) {
      slide.addText('CALL TO ACTION', {
        x: colX, y: colY, w: 4, h: 0.25,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      slide.addText(trim(post.cta, 200), {
        x: colX, y: colY + 0.3, w: 4, h: 0.7,
        fontSize: 11, fontFace: theme.font, color: theme.fg, bold: true, valign: 'top',
      });
      colY += 1.1;
    }
    const tags = parseJsonish(post.hashtags) || [];
    if (Array.isArray(tags) && tags.length > 0) {
      slide.addText('TAGS', {
        x: colX, y: colY, w: 4, h: 0.25,
        fontSize: 9, fontFace: theme.font, color: theme.muted, bold: true, charSpacing: 3,
      });
      const tagText = tags.slice(0, 12).map((t: any) => `#${String(t).replace(/^#/, '')}`).join(' ');
      slide.addText(tagText, {
        x: colX, y: colY + 0.3, w: 4, h: 0.6,
        fontSize: 9, fontFace: theme.font, color: theme.muted, valign: 'top',
      });
    }

    // Footer rule + slide number
    slide.addShape(pptx.ShapeType.line, {
      x: 0.7, y: 6.85, w: 12, h: 0,
      line: { color: theme.rule, width: 0.5 },
    });
    slide.addText(client.name, {
      x: 0.7, y: 6.95, w: 6, h: 0.3,
      fontSize: 9, fontFace: theme.font, color: theme.muted,
    });
    slide.addText(`${i + 1} / ${totalPosts + 3}`, {
      x: 9.7, y: 6.95, w: 3, h: 0.3,
      fontSize: 9, fontFace: theme.font, color: theme.muted, align: 'right',
    });
  }

  // ─── Summary slide ───────────────────────────────────────────────────
  updateJob(job.id, { progress: 92 });
  const summary = pptx.addSlide();
  summary.background = { color: theme.bg };

  summary.addText('IN SUMMARY', {
    x: 0.7, y: 0.5, w: 12, h: 0.3,
    fontSize: 10, fontFace: theme.font, color: theme.accent, bold: true, charSpacing: 4,
  });
  summary.addText(`${calendarMonth.month} at a glance`, {
    x: 0.7, y: 0.85, w: 12, h: 0.7,
    fontSize: 32, fontFace: theme.font, color: theme.fg, bold: true,
  });

  const platformCounts: Record<string, number> = {};
  const pillarCounts: Record<string, number> = {};
  for (const p of posts as any[]) {
    if (p.platform) platformCounts[p.platform] = (platformCounts[p.platform] || 0) + 1;
    if (p.pillar) pillarCounts[p.pillar] = (pillarCounts[p.pillar] || 0) + 1;
  }

  const platformRows: any[][] = [
    [
      { text: 'Platform', options: { bold: true, color: theme.fg, fill: { color: theme.card }, fontSize: 11 } },
      { text: 'Posts', options: { bold: true, color: theme.fg, fill: { color: theme.card }, fontSize: 11 } },
    ],
    ...Object.entries(platformCounts).map(([p, n]) => [
      { text: p, options: { color: platformColor(p), fontSize: 11 } },
      { text: String(n), options: { color: theme.fg, fontSize: 11 } },
    ]),
  ];
  summary.addTable(platformRows, {
    x: 0.7, y: 2.0, w: 5.5,
    border: { type: 'solid', pt: 0.5, color: theme.rule },
    rowH: 0.4,
  });

  if (Object.keys(pillarCounts).length > 0) {
    const pillarRows: any[][] = [
      [
        { text: 'Pillar', options: { bold: true, color: theme.fg, fill: { color: theme.card }, fontSize: 11 } },
        { text: 'Posts', options: { bold: true, color: theme.fg, fill: { color: theme.card }, fontSize: 11 } },
      ],
      ...Object.entries(pillarCounts).map(([p, n]) => [
        { text: p, options: { color: theme.accent, fontSize: 11 } },
        { text: String(n), options: { color: theme.fg, fontSize: 11 } },
      ]),
    ];
    summary.addTable(pillarRows, {
      x: 7.0, y: 2.0, w: 5.6,
      border: { type: 'solid', pt: 0.5, color: theme.rule },
      rowH: 0.4,
    });
  }

  summary.addText(`Generated by Radix Media · ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}`, {
    x: 0.7, y: 6.8, w: 12, h: 0.3,
    fontSize: 9, fontFace: theme.font, color: theme.muted, italic: true,
  });

  // ─── Write file ──────────────────────────────────────────────────────
  updateJob(job.id, { progress: 96 });
  const hash = crypto.randomBytes(6).toString('hex');
  const slug = client.slug || client.name.toLowerCase().replace(/\s+/g, '-');
  const monthSlug = calendarMonth.month.replace(/\s+/g, '_');
  const filename = `report_${slug}_${monthSlug}_${hash}.pptx`;
  const filePath = path.join(REPORT_DIR, filename);
  await pptx.writeFile({ fileName: filePath });

  const fileUrl = `/uploads/reports/${filename}`;
  await db.exportJob.create({
    data: {
      clientId: client.id,
      calendarMonthId: calendarMonth.id,
      type: `report-pptx-${themeName}`,
      status: 'completed',
      fileUrl,
    },
  });

  updateJob(job.id, { progress: 100 });
  return { fileUrl, filename, postCount: totalPosts };
}
